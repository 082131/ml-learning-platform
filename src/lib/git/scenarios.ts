/**
 * Starting points for the Git sandbox. `setup` runs before the learner's first command (silently, but on the
 * same clock); `suggested` is the guided path the lesson walks through. sim.test.ts replays setup + suggested,
 * plus `extra` scripts that exercise error paths, in real Git and compares the results.
 */
